def _is_empty(v: Any) -> bool:
    if v is None:
        return True
    s = str(v).strip().lower()
    return s in ("", "null", "nu11", "none")

def get_other_icd_codes_by_name(name: str, size: int = 5) -> List[str]:
    """
    根据手术名称查询文档，仅提取字段名以“另编码”开头且包含“icd”的值，返回去重列表。
    """
    query = {
        "bool": {
            "should": [
                {"term": {"name.keyword": name}},
                {"match_phrase": {"name": name}},
                {"match_phrase": {"t name": name}},
                {"match_phrase": {"t_name": name}},
                {"match_phrase": {"名称": name}},
                {"match_phrase": {"手术名称": name}},
            ],
            "minimum_should_match": 1,
        }
    }

    resp = es.search(index=INDEX_NAME, query=query, size=size, track_total_hits=True)
    hits = resp.get("hits", {}).get("hits", [])

    codes: Set[str] = set()
    for hit in hits:
        src = hit.get("_source", {}) or {}
        for k, v in src.items():
            if isinstance(k, str) and k.startswith("另编码") and "icd" in k.lower():
                if not _is_empty(v):
                    codes.add(str(v).strip())

    # 返回排序后的去重列表
    return sorted(codes)

