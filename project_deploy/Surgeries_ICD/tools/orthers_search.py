def get_name_by_icd_code(icd_code):
    """
    根据 ICD 编码精确查询，返回所有匹配的手术名称（去重）。
    - 同时支持主字段 icd_code 与 “另编码icd*” 字段精确匹配
    - 仅收集真正等于 icd_code 的文档名称，避免误收集
    """

    # 需要参与精确匹配的字段（可按你的索引扩展范围）
    icd_fields = ["icd_code"]
    
    # 构造 should term 查询，全部使用 keyword 子字段以保证精确匹配
    should_terms = []
    for f in icd_fields:
        should_terms.append({"term": {f"{f}.keyword": icd_code}})

    search_body = {
        "query": {
            "bool": {
                "should": should_terms,
                "minimum_should_match": 1
            }
        }
    }

    res = es.search(index=INDEX_NAME, body=search_body, size=200)
    total = res.get("hits", {}).get("total", {}).get("value", 0)
    if total == 0:
        return None

    # 兼容多种名称字段
    name_fields = ["name"]

    names_set = set()
    for hit in res["hits"]["hits"]:
        src = hit.get("_source", {}) or {}


        # 收集名称
        for nf in name_fields:
            if nf in src and src[nf] is not None and str(src[nf]).strip():
                names_set.add(str(src[nf]).strip())

    return sorted(names_set) if names_set else None


